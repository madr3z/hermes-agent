import XCTest
@testable import HermesGateway

final class ChatActivityTests: XCTestCase {
    private func event(_ type: String, _ payload: [String: JSON] = [:], runtime: String = "runtime", profile: String = "writer") -> JSON {
        .object(["type": .string(type), "session_id": .string(runtime), "profile": .string(profile), "payload": .object(payload)])
    }
    private func connected() -> ChatActivityState {
        var activity = ChatActivityState(profile: "writer")
        activity.bind(runtimeID: "runtime", snapshot: .object(["running": .bool(false)]))
        return activity
    }
    func testAcceptedSendShowsThinkingThenActualReplyAndClearsOnCompletionBeforeLateAck() {
        var activity = connected()
        let receipt = activity.beginSubmission()
        XCTAssertEqual(activity.phase, .sending)
        activity.submissionAccepted(receipt, result: .object(["status": .string("accepted")]))
        XCTAssertEqual(activity.phase, .thinking)
        XCTAssertTrue(activity.isAnimating)
        activity.receive(event("message.start"))
        activity.receive(event("message.delta", ["text": .string("Hello")]))
        XCTAssertEqual(activity.phase, .responding)
        activity.receive(event("message.complete", ["status": .string("complete")]))
        XCTAssertEqual(activity.phase, .completed)
        XCTAssertFalse(activity.isVisible)
        activity.receive(event("status.update", ["kind": .string("lifecycle"), "text": .string("Old status")]))
        activity.receive(event("message.delta", ["text": .string("late text")]))
        activity.submissionAccepted(receipt, result: .object(["status": .string("accepted")]))
        XCTAssertEqual(activity.phase, .completed)

        let raced = activity.beginSubmission()
        activity.receive(event("message.start"))
        activity.receive(event("message.complete", ["status": .string("complete")]))
        activity.submissionAccepted(raced, result: .object(["status": .string("accepted")]))
        XCTAssertFalse(activity.isAnimating)
        XCTAssertEqual(activity.phase, .completed)
    }
    func testToolsAndDisplayableProgressNeverStoreReasoningOrSpinnerFiller() {
        var activity = connected()
        activity.receive(event("message.start"))
        activity.receive(event("reasoning.delta", ["text": .string("private model reasoning")]))
        XCTAssertEqual(activity.phase, .thinking)
        XCTAssertNil(activity.detail)
        activity.receive(event("thinking.delta", ["text": .string("◉_◉ cogitating...")]))
        XCTAssertNil(activity.detail)
        activity.receive(event("thinking.delta", ["text": .string("⏳ waiting on provider — 30s with no output yet")]))
        XCTAssertEqual(activity.detail, "⏳ waiting on provider — 30s with no output yet")
        activity.receive(event("tool.start", ["tool_id": .string("one"), "name": .string("search"), "context": .string("Searching the selected folder")]))
        activity.receive(event("tool.start", ["tool_id": .string("two"), "name": .string("read")]))
        XCTAssertEqual(activity.phase, .tool)
        activity.receive(event("tool.complete", ["tool_id": .string("two"), "name": .string("read")]))
        XCTAssertEqual(activity.phase, .tool)
        XCTAssertEqual(activity.detail, "Running search")
        activity.receive(event("tool.complete", ["tool_id": .string("one"), "name": .string("search"), "summary": .string("Found three files")]))
        XCTAssertEqual(activity.phase, .thinking)
        XCTAssertEqual(activity.detail, "Found three files")
        activity.receive(event("status.update", ["kind": .string("compacting"), "text": .string("Summarizing context")]))
        XCTAssertEqual(activity.detail, "Summarizing context")
        activity.receive(event("reasoning.available", ["text": .string("another private thought")]))
        XCTAssertNil(activity.detail)
    }
    func testReconnectRestoresRunningWaitingStreamingAndIdleWithoutCreatingWork() {
        var activity = connected()
        activity.bind(runtimeID: "runtime", snapshot: .object(["running": .bool(true)]))
        XCTAssertEqual(activity.phase, .thinking)
        activity.bind(runtimeID: "runtime", snapshot: .object(["running": .bool(true), "inflight": .object(["assistant": .string("Partial reply"), "streaming": .bool(true)])]))
        XCTAssertEqual(activity.phase, .responding)
        activity.bind(runtimeID: "runtime", snapshot: .object(["running": .bool(true), "pending_approval": .object(["request_id": .string("approval-one")])]))
        XCTAssertEqual(activity.phase, .waitingForInput)
        XCTAssertFalse(activity.isAnimating)
        activity.receive(event("request.cancel", ["id": .string("approval-one"), "reason": .string("resolved")]))
        XCTAssertEqual(activity.phase, .thinking)
        activity.bind(runtimeID: "runtime", snapshot: .object(["running": .bool(false)]))
        XCTAssertEqual(activity.phase, .idle)
        XCTAssertFalse(activity.isVisible)
    }
    func testScopeAndTerminalPathsCannotLeaveAnAnimatingIndicator() {
        var activity = connected()
        activity.receive(event("message.start", profile: "other"))
        activity.receive(event("message.start", runtime: "other"))
        XCTAssertEqual(activity.phase, .idle)
        activity.receive(event("message.start"))
        activity.interrupted(.object(["status": .string("not_interrupted")]))
        XCTAssertTrue(activity.isAnimating)
        activity.interrupted(.object(["status": .string("interrupted")]))
        XCTAssertEqual(activity.phase, .cancelled)
        XCTAssertFalse(activity.isAnimating)
        activity.receive(event("message.start"))
        activity.receive(event("message.complete", ["status": .string("error"), "error": .string("Provider unavailable")]))
        XCTAssertEqual(activity.phase, .failed)
        XCTAssertEqual(activity.detail, "Provider unavailable")
        XCTAssertFalse(activity.isAnimating)
        let receipt = activity.beginSubmission()
        activity.disconnect()
        activity.submissionAccepted(receipt, result: .object([:]))
        XCTAssertEqual(activity.phase, .disconnected)
        XCTAssertFalse(activity.isAnimating)
        activity.bind(runtimeID: "replacement", snapshot: .object(["running": .bool(false)]))
        activity.receive(event("message.start"))
        XCTAssertEqual(activity.phase, .idle)
    }
    func testQueuedSendAndEarlyIdleInfoDoNotMaskRunningOrGetStuckAfterRealIdle() {
        var activity = connected()
        let receipt = activity.beginSubmission()
        activity.receive(event("session.info", ["running": .bool(false)]))
        XCTAssertEqual(activity.phase, .sending)
        activity.submissionAccepted(receipt, result: .object(["status": .string("queued")]))
        activity.receive(event("session.info", ["running": .bool(false)]))
        XCTAssertEqual(activity.phase, .queued)
        activity.receive(event("message.start"))
        let queued = activity.beginSubmission()
        activity.submissionAccepted(queued, result: .object(["status": .string("queued")]))
        XCTAssertEqual(activity.phase, .thinking)
        activity.receive(event("session.info", ["running": .bool(false)]))
        XCTAssertEqual(activity.phase, .completed)
        XCTAssertFalse(activity.isAnimating)
        let refused = activity.beginSubmission()
        activity.submissionFailed(refused, message: "Request refused")
        XCTAssertEqual(activity.phase, .failed)
    }
    func testConnectionWaitSettlesOnlyItsOwnRequestAndErrorsClearIt() {
        var activity = connected()
        activity.receive(event("message.start"))
        activity.receive(event("connection.request", ["op_id": .string("login")]))
        XCTAssertEqual(activity.phase, .waitingForInput)
        activity.receive(event("connection.update", ["op_id": .string("other"), "settled": .bool(true)]))
        XCTAssertEqual(activity.phase, .waitingForInput)
        activity.receive(event("connection.update", ["op_id": .string("login"), "settled": .bool(true)]))
        XCTAssertEqual(activity.phase, .thinking)
        activity.receive(event("connection.request", ["op_id": .string("login")]))
        activity.receive(event("error", ["message": .string("Connection lost")]))
        XCTAssertEqual(activity.phase, .failed)
        XCTAssertFalse(activity.isAnimating)
    }
}
